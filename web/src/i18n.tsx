export const MESSAGES: Record<Lang, Messages> = { zh, en };

/** 默认语言：浏览器语言里第一个认得出的；都认不出用中文。 */
export function detectLang(languages: readonly string[]): Lang {
  for (const tag of languages) {
    const base = tag.toLowerCase().split("-")[0];
    if (base === "zh") return "zh";
    if (base === "en") return "en";
  }
  return "zh";
}

export function translate(lang: Lang, key: MessageKey, params: Record<string, string | number> = {}): string {
  const template = MESSAGES[lang][key] ?? MESSAGES.zh[key];
  return template.replace(/\{(\w+)\}/g, (whole, name: string) =>
    name in params ? String(params[name]) : whole,
  );
}

export type T = (key: MessageKey, params?: Record<string, string | number>) => string;

const LangContext = createContext<{ lang: Lang; t: T }>({
  lang: "zh",
  t: (key, params) => translate("zh", key, params),
});

export function LangProvider({ lang, children }: { lang: Lang; children: ReactNode }) {
  const t: T = (key, params) => translate(lang, key, params);
  return <LangContext.Provider value={{ lang, t }}>{children}</LangContext.Provider>;
}

export function useT(): T {
  return useContext(LangContext).t;
}

export function useLang(): Lang {
  return useContext(LangContext).lang;
}
